"""Build the generated pages of docs/: the tree, and where each number lives.

    python -m scripts.repo.build_docs_index          write them
    python -m scripts.repo.build_docs_index --check  fail if they are out of date

Code comments and older notes cite section numbers (31.19), decisions (D110) and
measurements (M27). The three pages in docs/reference/ say which file holds each.
docs/SUMMARY.md is the whole tree, in the form mdBook reads.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2] / "docs"
NOTE = "Generated by `python -m scripts.repo.build_docs_index`. Do not edit by hand.\n"
FOLDERS = (
    ("status", "Status: where the project stands"),
    ("rules", "Rules: how we work"),
    ("product", "Product"),
    ("development", "Development"),
    ("architecture", "Architecture"),
    ("agent", "Agent"),
    ("llm", "Models, providers and quotas"),
    ("retrieval", "Retrieval"),
    ("prompts", "Prompts"),
    ("step0", "Step 0: the walking skeleton"),
    ("step1", "Step 1: the RAG system"),
    ("step2", "Step 2: the agent"),
    ("step3", "Step 3: the deployment"),
    ("step4", "Step 4: the fine-tuning"),
    ("reference", "Reference"),
    ("slice8", "Evidence: slice 8, run 1"),
    ("slice8v2", "Evidence: slice 8, run 2"),
    ("slice8v3", "Evidence: slice 8, run 3"),
    ("archive", "Archive: older full text"),
)


def slug(heading: str) -> str:
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", heading)
    text = re.sub(r"[*`]", "", text).strip().lower()
    return re.sub(r"[^\w\- ]", "", text).replace(" ", "-")


def headings(path: Path) -> list[str]:
    found, code = [], False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.lstrip().lstrip("> ").startswith(("```", "~~~")):
            code = not code
        elif not code and (match := re.match(r"^(?:> )?#{1,4} (.*)", line)):
            found.append(match.group(1))
    return found


def title(path: Path) -> str:
    return headings(path)[0] if headings(path) else path.stem


def pages() -> list[Path]:
    """Every hand-kept page (not the archive, which repeats older text)."""
    # slice8*: those reports number their own decisions D1.. and M1.. again.
    skip = {"archive", "reference", "slice8", "slice8v2", "slice8v3"}
    return sorted(
        path
        for path in ROOT.rglob("*.md")
        if path.relative_to(ROOT).parts[0] not in skip and path.parent != ROOT
    )


def summary() -> str:
    lines = ["# Summary", "", NOTE, "[Docs home](README.md)", ""]
    for folder, name in FOLDERS:
        lines += [f"## {name}", ""]
        for path in sorted((ROOT / folder).rglob("*.md")):
            link = path.relative_to(ROOT).as_posix()
            lines.append(f"- [{title(path)}]({link})")
        lines.append("")
    return "\n".join(lines)


def section_map() -> str:
    rows = []
    for path in pages():
        where = path.relative_to(ROOT).as_posix()
        for heading in headings(path):
            match = re.match(r"(\d+[a-z]?(?:\.\d+[a-z]?)?)\.? (.+)", heading)
            if match and path.parent.name in ("step2", "step3"):
                part = match.group(1)
                rows.append((part, match.group(2), where, slug(heading)))

    def order(row: tuple[str, str, str, str]) -> list[tuple[int, str]]:
        return [
            (int(re.match(r"\d+", p).group()), p)  # type: ignore[union-attr]
            for p in row[0].split(".")
        ]

    lines = [
        "# Section map (Step 2 and Step 3 numbers)",
        "",
        NOTE,
        "[Docs home](../README.md)",
        "",
        "The numbers 1 to 16 that older notes call *Step 1, slice 7 sections* are in "
        "[the ask path](../step1/ask-path.md).",
        "",
        "| section | title | page |",
        "|---|---|---|",
    ]
    for number, text, where, anchor in sorted(rows, key=order):
        lines.append(
            f"| {number} | {text.replace('|', '/')} | [{where}](../{where}#{anchor}) |"
        )
    return "\n".join(lines) + "\n"


def numbered(letter: str, name: str) -> str:
    """The table rows that define D1, D2, ... (or M1, ...), and their page."""
    row = re.compile(rf"^\|\s*(?:\*\*)?({letter}\d+)(?:\*\*)?\s*\|\s*(.+)")
    found: dict[str, list[tuple[str, str]]] = {}
    for path in pages():
        for line in path.read_text(encoding="utf-8").splitlines():
            if match := row.match(line):
                text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", match.group(2))
                text = re.sub(r"[*|~]", "", text).strip()
                short = text if len(text) <= 160 else text[:157].rstrip() + "..."
                where = path.relative_to(ROOT).as_posix()
                found.setdefault(match.group(1), []).append((short, where))
    lines = [
        f"# {name}",
        "",
        NOTE,
        "[Docs home](../README.md)",
        "",
        f"The first words only: open the page for the whole text. A number that was "
        f"changed later has more than one row. {letter} numbers written only in "
        f"running text are not in this table; search docs/ for them.",
        "",
        "| # | starts with | page |",
        "|---|---|---|",
    ]
    for key in sorted(found, key=lambda k: int(k[1:])):
        for short, where in found[key]:
            lines.append(f"| {key} | {short} | [{where}](../{where}) |")
    return "\n".join(lines) + "\n"


def generated() -> dict[str, str]:
    return {
        "reference/section-map.md": section_map(),
        "reference/decisions.md": numbered("D", "Decisions"),
        "reference/measurements.md": numbered("M", "Measurements"),
    }


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for name, text in generated().items():
        path = ROOT / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(name)
            if not check:
                path.parent.mkdir(exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    # Last, because it lists the pages written above.
    tree = ROOT / "SUMMARY.md"
    if not tree.exists() or tree.read_text(encoding="utf-8") != summary():
        stale.append("SUMMARY.md")
        if not check:
            tree.write_text(summary(), encoding="utf-8", newline="\n")
    if check and stale:
        print("out of date:", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
